#include "ft_push_swap.h"

void	ft_swap(t_pile **a)
{
	int	tmp;
	
	if (!*a || !a)
		return ;
	tmp = (*a)->value;
	(*a)->value = (*a)->next->value;
	(*a)->next->value = tmp;
}
