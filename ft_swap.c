#include "ft_push_swap.h"

void	ft_swap(t_pile **a)
{
	t_pile *tmp;
	
	if (!*a || !a)
		return ;
	tmp = (*a)->value;
	(*a)->next = (*a)->next->value;
	(*a)->next->value = tmp;
}
